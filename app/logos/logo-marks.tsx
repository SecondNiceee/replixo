/**
 * Девять знаков Replixo — только сам символ, без подписи.
 *
 * Все девять рисуются в системе координат 48×48 и наследуют цвет через
 * currentColor / var(--primary): знак должен одинаково работать в шапке
 * лендинга, в тёмном кабинете и на favicon, поэтому ни один цвет не вбит
 * литералом.
 *
 * Смысловая рамка у всех одна: «Replixo» — это реплика, отражение, повтор
 * сигнала. Отсюда мотивы: зеркальная симметрия, две встречные формы, дубль
 * контура. Камера-скруглённый-прямоугольник (текущий знак) намеренно не
 * повторяется больше одного раза: она есть у каждого второго сервиса звонков.
 */

interface MarkProps {
  className?: string
}

/** Общая обёртка: одна и та же система координат и правила у всех знаков. */
function Svg({ children, className }: { children: React.ReactNode; className?: string }) {
  return (
    <svg
      viewBox="0 0 48 48"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      className={className}
      aria-hidden="true"
    >
      {children}
    </svg>
  )
}

/* -------------------------------------------------------------------------- */
/* 1. Reply Bracket — две встречные угловые скобки                             */
/* -------------------------------------------------------------------------- */
/* Знак читается как «< >» — ответ и реплика. Скобки не смыкаются: зазор в
   центре и есть канал связи. */
export function MarkBracket({ className }: MarkProps) {
  return (
    <Svg className={className}>
      <path
        d="M19 12 8 24l11 12"
        stroke="currentColor"
        strokeWidth="4"
        strokeLinecap="round"
        strokeLinejoin="round"
      />
      <path
        d="M29 12l11 12-11 12"
        stroke="currentColor"
        strokeWidth="4"
        strokeLinecap="round"
        strokeLinejoin="round"
        opacity="0.45"
      />
    </Svg>
  )
}

/* -------------------------------------------------------------------------- */
/* 2. Mirror R — литера R и её отражение                                       */
/* -------------------------------------------------------------------------- */
/* Монограмма из двух половин: сплошная слева и её реплика справа, повёрнутая
   на 180°. Буква узнаётся, но не выглядит просто набранной шрифтом. */
export function MarkMirrorR({ className }: MarkProps) {
  return (
    <Svg className={className}>
      {/* Полная литера R: стойка, чаша и вынесенная нога. Вторая чаша снизу
          превращала знак в «B», поэтому реплика вынесена не в букву, а рядом с
          ней — отражённая нога-штрих (ниже). */}
      <path
        d="M14 40V8h9.5a8 8 0 0 1 0 16H14l12 16"
        stroke="currentColor"
        strokeWidth="4.5"
        strokeLinecap="round"
        strokeLinejoin="round"
      />
      {/* Реплика ноги: тот же наклон, зеркально вверх. Полупрозрачная —
          получается R со своим отражением, а не просто набранная буква. */}
      <path
        d="M26 8 14 24"
        stroke="currentColor"
        strokeWidth="4.5"
        strokeLinecap="round"
        opacity="0.4"
      />
    </Svg>
  )
}

/* -------------------------------------------------------------------------- */
/* 3. Echo Rings — сигнал и две его волны                                      */
/* -------------------------------------------------------------------------- */
/* Точка в центре — источник, дуги — расходящийся эфир. Ослабление opacity
   наружу читается как затухание, а не как декоративный градиент. */
