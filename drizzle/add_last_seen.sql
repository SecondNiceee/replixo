-- Время последнего присутствия пользователя.
--
-- Зачем колонка в БД, а не Map в памяти сокет-сервера: presence эфемерен по
-- своей природе (жив, пока жив websocket), но «был(а) 5 минут назад» — это
-- ИСТОРИЯ. В памяти она умирала вместе с процессом: после каждого деплоя все
-- друзья показывались как «не в сети» без времени, потому что значение
-- появлялось только в момент дисконнекта и только у тех, кто успел
-- подключиться при жизни этого процесса.
--
-- Значение обновляется не только на разрыве, но и периодически, пока
-- пользователь онлайн (см. LAST_SEEN_FLUSH_MS в server/src/dm/presence.ts).
-- Поэтому даже жёсткое падение процесса оставляет достоверное время с
-- погрешностью не больше интервала сброса.
ALTER TABLE "user" ADD COLUMN IF NOT EXISTS "lastSeenAt" timestamp;

-- Индекс не нужен: колонка всегда читается по "user"."id" (первичный ключ),
-- в том числе в выборке presence по списку друзей через id = ANY($1).
