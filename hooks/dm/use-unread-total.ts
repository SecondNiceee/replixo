'use client'

import { useConversations } from '@/hooks/dm/use-conversations'

// ---------------------------------------------------------------------------
// Суммарное число непрочитанных сообщений — для бейджей вне страницы чата.
//
// Тонкая обёртка над useConversations: ключ SWR тот же, что у страницы чата,
// поэтому список не загружается повторно и оба места всегда показывают одно и
// то же число. Погасив счётчик в открытом диалоге, страница правит тот же
// кэш — бейдж в шапке перерисовывается сам.
//
// Хук только читает: звук и заголовок вкладки — забота DmNotifier, ровно
// одного на приложение. Поэтому вызывать этот хук можно из любого числа
// компонентов.
// ---------------------------------------------------------------------------

export { CONVERSATIONS_KEY } from '@/hooks/dm/use-conversations'

export function useUnreadTotal(): number {
  // selfId и activeId не передаём: вне страницы чата открытого диалога нет, а
  // любое прочтение здесь стоит считать поводом перечитать счётчик.
  const { totalUnread } = useConversations()
  return totalUnread
}
