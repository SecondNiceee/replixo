'use client'

import { useEffect, useState } from 'react'

// ---------------------------------------------------------------------------
// Тикающие «сейчас» для относительного времени («был(а) 5 минут назад»).
//
// Проблема, которую это решает: строка статуса считается один раз при рендере, а
// событий больше не будет — оффлайн пришёл однажды. Открытый час кабинет
// показывал бы «был(а) только что» у человека, которого не видели час.
//
// Один общий интервал на все подписчики, а не свой на каждый компонент: строк
// со временем на экране десятки (список диалогов), и десятки таймеров, каждый
// со своей фазой, дёргали бы рендер вразнобой.
//
// Ререндер компонента вызывается только пока он подписан — а подписываться
// стоит лишь тогда, когда время реально видно (см. enabled).
// ---------------------------------------------------------------------------

/**
 * Шаг тика. Формулировки округлены до минут, поэтому чаще незачем: полминуты —
 * максимальное отставание строки от истины, и оно незаметно.
 */
const TICK_MS = 30_000

const subscribers = new Set<(now: number) => void>()
let timer: ReturnType<typeof setInterval> | null = null

function subscribe(fn: (now: number) => void): () => void {
  subscribers.add(fn)
  if (!timer) {
    timer = setInterval(() => {
      const now = Date.now()
      for (const subscriber of subscribers) subscriber(now)
    }, TICK_MS)
  }
  return () => {
    subscribers.delete(fn)
    // Последний ушёл — таймер держать не за чем.
    if (subscribers.size === 0 && timer) {
      clearInterval(timer)
      timer = null
    }
  }
}

/**
 * Текущее время, обновляемое раз в TICK_MS.
 *
 * `enabled: false` отключает подписку, не меняя правила хуков: строку времени
 * видно только у оффлайн-собеседника, и обновлять её для остальных незачем.
 */
export function useNow(enabled = true): number {
  const [now, setNow] = useState(() => Date.now())

  useEffect(() => {
    if (!enabled) return
    // Пока хук был отключён, тики проходили мимо — синхронизируемся сразу,
    // иначе первая отрисовка показала бы время момента монтирования.
    setNow(Date.now())
    return subscribe(setNow)
  }, [enabled])

  return now
}
