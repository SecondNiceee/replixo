// ---------------------------------------------------------------------------
// Адрес сокет-сервера для запросов «сервер → сервер» (маршруты /internal/*).
//
// Только для серверного кода: сюда ходят с INTERNAL_HOOK_SECRET, который не
// имеет префикса NEXT_PUBLIC_ и в браузерный бандл попасть не должен.
//
// Фолбэком нельзя брать NEXT_PUBLIC_MEDIASOUP_URL: в проде это публичный origin,
// а nginx не проксирует /internal/ на порт 3001 — запрос ушёл бы в Next и молча
// получил 404. К тому же /internal/ и не должен быть доступен извне. Ходим
// напрямую внутри VPS.
//
// Функция, а не константа: значение читается в момент вызова, поэтому модуль
// можно импортировать и там, где переменные окружения появляются позже.
// ---------------------------------------------------------------------------

export function serverBaseUrl(): string {
  const raw = process.env.MEDIASOUP_URL ?? 'http://127.0.0.1:3001'
  return raw.replace(/\/+$/, '')
}
