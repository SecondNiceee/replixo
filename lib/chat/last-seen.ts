// Время последнего присутствия — напрямую из Postgres, без сокет-сервера.
//
// Зачем дубль, если lastSeenAt уже приходит в ответе /internal/presence: тот
// ответ доступен только когда сокет-сервер отвечает И задан общий секрет. Пока
// секрет не настроен (а это состояние по умолчанию: в .env.example переменная
// пустая), снапшот приходил пустым, и КАЖДАЯ строка списка друзей подписывалась
// «Подключение…» до самого подключения websocket — примерно секунда на каждое
// открытие кабинета.
//
// Половину этих данных Next может прочитать сам: статус online эфемерен и живёт
// только в памяти сокет-сервера, а lastSeenAt лежит в "user"."lastSeenAt", то
// есть в той же БД, из которой страница и так читает список друзей. Одного
// времени достаточно, чтобы про большинство друзей сказать правду сразу (см.
// LAST_SEEN_PROVES_OFFLINE_MS).
//
// Только для серверного кода: тянет за собой пул подключений к БД.
// ---------------------------------------------------------------------------

import { inArray } from 'drizzle-orm'
import { db } from '@/lib/db'
import { user } from '@/lib/db/schema'

/**
 * userId → когда человека видели последний раз (мс).
 *
 * Никогда не бросает: время последнего присутствия — украшение поверх списка, и
 * упавший запрос не должен превращать кабинет в 500. В худшем случае вернётся
 * пустой объект, и подписи дождутся websocket, как и раньше.
 *
 * NULL в колонке (пользователь ни разу не подключался) пропускаем: ключ должен
 * отсутствовать, иначе на клиенте пришлось бы отличать «нет данных» от нуля.
 */
export async function fetchLastSeen(userIds: string[]): Promise<Record<string, number>> {
  if (userIds.length === 0) return {}

  try {
    const rows = await db
      .select({ id: user.id, lastSeenAt: user.lastSeenAt })
      .from(user)
      .where(inArray(user.id, userIds))

    const result: Record<string, number> = {}
    for (const row of rows) {
      if (row.lastSeenAt) result[row.id] = row.lastSeenAt.getTime()
    }
    return result
  } catch (e) {
    console.error('[presence] lastSeenAt не прочитан из БД:', (e as Error).message)
    return {}
  }
}
