// ---------------------------------------------------------------------------
// Идентификация СОЕДИНЕНИЯ-ИНИЦИАТОРА действия с дружбой.
//
// Зачем это нужно. Комнаты сокет-сервера адресуются по пользователю
// (`user:<id>`), поэтому `dm:friends:changed` приходит во ВСЕ вкладки и
// устройства обоих участников. Инициатор при этом обновляет свои списки сам —
// сразу по ответу API. Раньше эхо гасилось по userId, из-за чего вторая вкладка
// инициатора получала событие и выбрасывала его, хотя ничего не перечитывала:
// её списки оставались устаревшими до перезагрузки страницы.
//
// Правильный критерий — соединение, а не пользователь. Браузер передаёт свой
// socket.id в этом заголовке, роут прокидывает его в сокет-сервер, а тот
// исключает ровно этот сокет из рассылки (и дублирует id в payload, чтобы
// клиент мог проверить сам).
//
// Модуль изоморфный: никаких server-only зависимостей, его импортируют и
// client-компоненты, и route handlers.
// ---------------------------------------------------------------------------

/** Заголовок, в котором браузер передаёт id своего websocket-соединения. */
export const ORIGIN_SOCKET_HEADER = 'x-origin-socket-id'

// socket.io выдаёт id из base64url-алфавита. Двоеточий в нём быть не может, и
// это важно: на сервере значение используется как имя комнаты в `.except()`, а
// наши комнаты выглядят как `user:<id>`.
const SOCKET_ID_RE = /^[A-Za-z0-9_-]{1,64}$/

/**
 * Прочитать id соединения-инициатора из запроса.
 *
 * `null` — заголовка нет или он битый: действие могли выполнить вообще без
 * websocket. Тогда событие получают все соединения инициатора, включая ту
 * вкладку, что уже обновилась. Лишняя ревалидация безобидна (SWR схлопнет
 * запросы), потеря обновления — нет.
 */
export function originSocketIdFromRequest(req: Request): string | null {
  const raw = req.headers.get(ORIGIN_SOCKET_HEADER)
  if (!raw || !SOCKET_ID_RE.test(raw)) return null
  return raw
}

/**
 * Заголовки для fetch из браузера. Пустой объект, если сокета ещё нет — тогда
 * дедупликация просто не применяется.
 */
export function originSocketHeaders(socketId?: string | null): Record<string, string> {
  return socketId && SOCKET_ID_RE.test(socketId) ? { [ORIGIN_SOCKET_HEADER]: socketId } : {}
}
