import { NextResponse } from 'next/server'

// ---------------------------------------------------------------------------
// Ограничение частоты мутирующих запросов дружбы.
//
// Зачем это здесь, а не только на сокет-сервере: /api/friends/* пишет в БД и
// на каждый успешный вызов инициирует рассылку. То есть один цикл
// «request → cancel → request → …» без лимита превращается в усилитель:
// сервер делает несколько запросов в Postgres и хук на сокет-сервер, а браузер
// жертвы на каждое событие перечитывает списки и центр уведомлений. Спам заявок
// тут даже не главная проблема.
//
// Реализация — окно в памяти процесса. Ограничения, которые надо помнить:
//
//   • счётчик НЕ общий между инстансами. На нескольких репликах реальный
//     потолок умножается на их число. Это осознанный компромисс: внешнего
//     хранилища (Redis) в проекте нет, а per-instance лимит уже отсекает
//     подавляющую часть автоматического спама;
//   • состояние теряется при перезапуске/засыпании инстанса, то есть лимит
//     «мягкий» — он про защиту от потока запросов, а не про квоты и биллинг.
//
// Если появится Upstash Redis (или любой общий стор), эту функцию нужно
// заменить на распределённый лимитер, не меняя вызовы в роутах: контракт
// (`enforceRateLimit` → NextResponse | null) специально сделан минимальным.
// ---------------------------------------------------------------------------

/** Метки времени попыток в пределах окна. Ключ — обычно `<действие>:<userId>`. */
const hits = new Map<string, number[]>()

/**
 * Сколько ключей допускаем в памяти до принудительной уборки. Ключей столько
 * же, сколько активных пользователей, поэтому предел щедрый — он существует
 * только чтобы забытые ключи не росли бесконечно на долгоживущем инстансе.
 */
const MAX_KEYS = 10_000

export interface RateLimitRule {
  /** Сколько запросов разрешено в окне. */
  limit: number
  /** Длина окна в миллисекундах. */
  windowMs: number
}

/**
 * Лимиты подобраны так, чтобы живой человек в них не упирался никогда.
 *
 * Отправка заявок строже остальных действий: это единственный роут, который
 * создаёт уведомление незнакомому человеку, то есть единственный способ
 * доставить незапрошенный шум чужому пользователю.
 */
export const FRIENDS_REQUEST_RULE: RateLimitRule = { limit: 12, windowMs: 60_000 }

/**
 * Ответы на заявки и удаление из друзей. Лимит выше, потому что разобрать
 * десяток накопившихся заявок подряд — нормальное поведение, а адресата такие
 * действия не спамят (заявку он уже видел).
 */
export const FRIENDS_MUTATION_RULE: RateLimitRule = { limit: 40, windowMs: 60_000 }

/**
 * Учесть попытку и сказать, не превышен ли лимит.
 *
 * Окно скользящее: храним метки времени и отбрасываем всё старше `windowMs`.
 * Фиксированное окно позволило бы отправить двойную порцию на его стыке, а
 * скользящее считает ровно последние N миллисекунд.
 */
function take(key: string, rule: RateLimitRule): { ok: boolean; retryAfterMs: number } {
  const now = Date.now()
  const windowStart = now - rule.windowMs

  // Уборка мусора привязана к размеру мапы, а не к таймеру: setInterval в
  // серверлес-окружении удерживал бы инстанс и не имел бы смысла между
  // вызовами. Сносим только ключи, у которых окно полностью истекло.
  if (hits.size > MAX_KEYS) {
    for (const [k, stamps] of hits) {
      if (stamps.length === 0 || stamps[stamps.length - 1] <= windowStart) hits.delete(k)
    }
  }

  const previous = hits.get(key) ?? []
  const recent = previous.filter((t) => t > windowStart)

  if (recent.length >= rule.limit) {
    // Освободится, когда самая старая попытка выпадет из окна.
    const retryAfterMs = recent[0] + rule.windowMs - now
    // Запись всё равно обновляем: отфильтрованный массив короче исходного.
    hits.set(key, recent)
    return { ok: false, retryAfterMs: Math.max(retryAfterMs, 0) }
  }

  recent.push(now)
  hits.set(key, recent)
  return { ok: true, retryAfterMs: 0 }
}

/**
 * Проверка для роута: `null` — можно продолжать, `NextResponse` — готовый 429,
 * который нужно вернуть немедленно.
 *
 * Ключом должен быть id пользователя из сессии, а НЕ IP: все мутирующие роуты
 * дружбы требуют авторизации, а IP за NAT и мобильным оператором общий на
 * многих людей — лимит по нему наказывал бы посторонних.
 */
export function enforceRateLimit(key: string, rule: RateLimitRule): NextResponse | null {
  const { ok, retryAfterMs } = take(key, rule)
  if (ok) return null

  const retryAfterSec = Math.max(1, Math.ceil(retryAfterMs / 1000))
  return NextResponse.json(
    { error: 'Слишком много запросов, попробуйте позже' },
    {
      status: 429,
      // Retry-After по стандарту в секундах: клиент (и любой автоматический
      // ретрай) узнаёт, когда осмысленно повторить.
      headers: { 'Retry-After': String(retryAfterSec) },
    },
  )
}
