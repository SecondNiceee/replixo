'use client'

// ---------------------------------------------------------------------------
// Статус вкладки для presence: единственное место, где решается, «на месте ли
// человек».
//
// Вынесено из use-presence-heartbeat, потому что тот же ответ нужен ДО того, как
// хук начнёт работать: статус передаётся в handshake сокета (см. use-dm-socket),
// иначе сервер вынужден был бы предполагать 'online' и открытая в фоне вкладка
// давала бы у друзей вспышку зелёной точки.
//
// Два экспортируемых входа сознательно разные:
//
//   • computeTabStatus — для хука, у которого есть история (когда потерян фокус,
//     когда была последняя активность);
//   • currentTabStatus — для handshake, где истории ещё нет и всё, что известно,
//     это текущее состояние документа.
// ---------------------------------------------------------------------------

/**
 * Что вкладка сообщает о себе серверу.
 *
 *   online — вкладка на экране и в фокусе. Бездействие сюда НЕ вмешивается:
 *            человек, читающий длинное сообщение или смотрящий видео, на месте.
 *   hidden — ушла в фон либо окно потеряло фокус дольше BLUR_AWAY_MS. Сервер
 *            считает это оффлайном (см. statusOf в server/src/dm/presence.ts),
 *            поэтому «ушёл в другой таб» выглядит у друзей как «был(а) в сети
 *            только что», а не как зелёная точка.
 *   call   — идёт разговор. Для друзей это то же, что online, но отдельное
 *            значение нужно серверу: свипер не понижает такие соединения по
 *            редкости пингов (см. PRESENCE_STALE_MS), потому что свёрнутое окно
 *            звонка — это как раз норма, а не признак отсутствия.
 *
 * Промежуточного «отошёл» здесь больше нет намеренно. Открытая на экране вкладка
 * — присутствие, и отсчитывать по ней бездействие оказалось вредно дважды: тот,
 * кто просто читает, желтел у собеседника на глазах, а уход «по тишине» ещё и
 * портил время последнего присутствия (подробно — в шапке presence.ts на
 * сервере). Уход теперь фиксируется только по настоящему событию: вкладка в фон
 * или потеря фокуса окном.
 */
export type TabStatus = 'online' | 'hidden' | 'call'

/**
 * Отсрочка оффлайна при потере фокуса окном, которое всё ещё видимо.
 *
 * Потеря фокуса — единственный признак того, что человек ушёл в другое
 * ПРИЛОЖЕНИЕ (игра, второй монитор, другое окно браузера): вкладка при этом
 * остаётся активной, visibilityState равен 'visible', и без учёта фокуса уход
 * вообще ничем себя не выдаёт.
 *
 * Но тот же blur даёт клик в адресную строку, в devtools или в системное окно
 * выбора файла — а это ещё не уход. Поэтому не гасим точку сразу, а объявляем
 * оффлайн, продержавшись без фокуса это окно.
 */
export const BLUR_AWAY_MS = 15_000

// --- Участие в звонке -------------------------------------------------------
//
// Звонок — это присутствие, причём самое сильное из возможных: человек прямо
// сейчас говорит. Но для остальных признаков он невидим — в разговоре мышь не
// двигают, а окно звонка сворачивают, чтобы работать в другой вкладке. Без этого
// флага собеседник видел бы «был(а) только что» у того, с кем в эту секунду
// разговаривает.
//
// Флаг держится модульной переменной, а не в React-состоянии, потому что его
// пишет страница комнаты, а читает heartbeat в DmNotifier — это разные ветки
// дерева, и общего родителя, кроме layout, у них нет. Значение эфемерно (живёт
// ровно пока открыта страница звонка), поэтому стор здесь был бы лишним.

let inCall = false

/**
 * Кому сообщить, что участие в звонке изменилось.
 *
 * Нужно потому, что вход в звонок и выход из него — единственные переходы,
 * которые не сопровождаются НИ ОДНИМ браузерным событием: ни visibilitychange,
 * ни focus, ни движения мыши. Без подписки статус доезжал бы только со
 * следующим опросом heartbeat, и собеседник до пяти секунд видел бы «был(а)
 * только что» у человека, который уже в разговоре.
 */
const callListeners = new Set<() => void>()

/**
 * Подписаться на изменение участия в звонке. Возвращает отписку.
 *
 * Подписка, а не React-состояние, потому что флаг пишет страница комнаты, а
 * читает heartbeat в DmNotifier: разные ветки дерева, общий родитель — только
 * layout.
 */
export function subscribeInCall(listener: () => void): () => void {
  callListeners.add(listener)
  return () => callListeners.delete(listener)
}

/**
 * Отметить, что вкладка находится в активном звонке. Вызывается страницей
 * комнаты на входе и, ОБЯЗАТЕЛЬНО, с false на выходе: иначе человек остался бы
 * «в сети» до перезагрузки страницы.
 */
export function setInCall(active: boolean): void {
  if (inCall === active) return
  inCall = active
  for (const listener of callListeners) listener()
}

export function isInCall(): boolean {
  return inCall
}

export interface TabActivity {
  /** Есть ли у окна фокус. */
  focused: boolean
  /** Когда фокус был потерян (0, если окно в фокусе). */
  focusLostAt: number
  /** Момент оценки. Параметром — чтобы функция осталась чистой и тестируемой. */
  now?: number
}

/**
 * Свести признаки присутствия в один статус.
 *
 * Одного visibilityState не хватает: вкладка, открытая в неактивном окне, поверх
 * которого идёт игра, остаётся 'visible', и человек «сидел в сети», играя.
 * Поэтому учитываются видимость вкладки и фокус окна (уход в другое приложение).
 *
 * Времени последней активности здесь сознательно нет. Молчание за открытой
 * вкладкой ничего не доказывает — читают, смотрят, думают, — а раньше именно оно
 * гасило точку и портило «был(а) N минут назад». Уход из-за стола с открытым и
 * сфокусированным окном мы теперь честно не отличаем от чтения: цена ошибки
 * несопоставима — лучше показать «в сети» ушедшему на минуту, чем оффлайн тому,
 * кто прямо сейчас читает.
 */
export function computeTabStatus({
  focused,
  focusLostAt,
  now = Date.now(),
}: TabActivity): TabStatus {
  // Звонок перебивает все остальные признаки: свёрнутое окно разговора — это
  // по-прежнему разговор. Отдельным значением, а не 'online', чтобы сервер не
  // понизил такое соединение своей эвристикой редких пингов: браузер душит
  // таймеры в фоновой вкладке, и без исключения статус мигал бы «оффлайн →
  // снова в сети» каждые полминуты разговора.
  if (inCall) return 'call'

  // Вкладка в фоне (переключились на другую, свернули окно) — hidden, и для
  // друзей это ровно оффлайн: точка гаснет, вместо неё «был(а) в сети только
  // что». Соединение при этом живёт, поэтому сообщения и звонки доходят.
  if (typeof document !== 'undefined' && document.visibilityState === 'hidden') return 'hidden'

  // Вкладка активна и «видима», но фокус ушёл в другое приложение. Это главная
  // дыра visibilityState: alt-tab в игру, второй монитор, другое окно браузера.
  // Считаем это уходом, но не мгновенно (см. BLUR_AWAY_MS): пока порог не
  // выдержан, человек всё ещё числится присутствующим — клик в адресную строку
  // не должен гасить точку у собеседника.
  if (!focused) {
    return now - focusLostAt >= BLUR_AWAY_MS ? 'hidden' : 'online'
  }

  // Вкладка на экране и в фокусе. Это и есть присутствие — больше проверять
  // нечего.
  return 'online'
}

/**
 * Статус вкладки «прямо сейчас», без истории — для handshake нового соединения.
 *
 * Истории на этот момент и не может быть: соединение только открывается. Зато
 * само состояние документа уже всё решает — вкладку, открытую в фоне
 * (Ctrl+click, восстановление сессии, реконнект свёрнутого браузера), видно
 * сразу, и сервер больше не обязан предполагать 'online'.
 *
 * Окно без фокуса на этот момент считается присутствием: отсчёт BLUR_AWAY_MS
 * начинается только сейчас, и объявлять оффлайн человеку, который открыл сайт и
 * на секунду отвлёкся, рано — дальше это уточнит heartbeat.
 */
export function currentTabStatus(): TabStatus {
  if (typeof document === 'undefined') return 'online'
  const now = Date.now()
  return computeTabStatus({
    focused: document.hasFocus(),
    focusLostAt: now,
    now,
  })
}
